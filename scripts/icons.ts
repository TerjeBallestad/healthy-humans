// Exports Terje's icons from assets/icons/icons.aseprite into src/kit/icons/: one 32x32 PNG per
// layer, named by the layer (scripts/icons.lua), and src/kit/icons.ts with an import for each. Run
// it after a change in Aseprite:
//   npm run icons
// CI has no Aseprite, so the output is committed. Layer names must be unique, or one PNG overwrites
// the other.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'assets/icons/icons.aseprite';
const OUT = 'src/kit/icons';

function aseprite(): string {
  const steam = join(
    process.env.HOME ?? '',
    'Library/Application Support/Steam/steamapps/common/Aseprite/Aseprite.app/Contents/MacOS/aseprite',
  );
  const app = '/Applications/Aseprite.app/Contents/MacOS/aseprite';
  return process.env.ASEPRITE ?? [steam, app].find(existsSync) ?? 'aseprite';
}
const BIN = aseprite();

const layers = execFileSync(BIN, ['-b', '--list-layers', SRC], { encoding: 'utf8' })
  .split('\n')
  .filter(Boolean);
const twice = layers.filter((l, i) => layers.indexOf(l) !== i);
if (twice.length) throw new Error(`Layer names used twice: ${twice.join(', ')}`);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
execFileSync(BIN, ['-b', SRC, '--script-param', `out=${OUT}`, '--script', 'scripts/icons.lua']);

const names = readdirSync(OUT)
  .filter((f) => f.endsWith('.png'))
  .map((f) => f.slice(0, -4))
  .sort();
const id = (name: string) => name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
writeFileSync(
  'src/kit/icons.ts',
  '// Generated by scripts/icons.ts from assets/icons/icons.aseprite. Do not edit.\n' +
    names.map((n) => `import ${id(n)} from './icons/${n}.png';\n`).join('') +
    '\nexport const ICONS = {\n' +
    names.map((n) => `  '${n}': ${id(n)},\n`).join('') +
    '};\n\nexport type IconName = keyof typeof ICONS;\n',
);
console.log(`${names.length} icons -> ${OUT}/: ${names.join(', ')}`);
